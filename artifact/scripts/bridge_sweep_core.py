"""
Shared core for the bridge sweep certificates (Phase 1 of the rigid-bridge rebuild).

Import-safe: importing this module performs NO sweeps and writes NO files.
No mutable global state for paths, seeds or outputs — everything is passed in.

Commutator convention (identical to the P1 suite, cf. a5_criterion.py):
    [a, b] = a * b * a^-1 * b^-1,   (p*q)(x) = p(q(x)).

Per-step tree model (identical to bridge_fixed_leaves_s5.py):
    leaf value set   V(leaf) = {e, sigma}
    gate value set   V(v)    = V(L) . V(R) . V(L)^-1 . V(R)^-1   (set product)
    W_j(c)           = V(c)  intersect  H_c^(j)
    at a gate v of level k with children L, R:
      (a)  validity    alpha_v != e  (alpha folds [alpha_L, alpha_R])
      (T)  tower       [H_L^(k-1), H_R^(k-1)] == H_v^(k)
      (S)  saturation  <[W_{k-1}(L), W_{k-1}(R)]> == [<W_{k-1}(L)>, <W_{k-1}(R)>]
"""
import itertools
import random

import numpy as np

# --------------------------------------------------------------------------
# Pure permutation helpers (tuples; no tables). Used by witness checks.
# --------------------------------------------------------------------------

def pmul(a, b):
    """(a*b)(x) = a(b(x))."""
    return tuple(a[b[i]] for i in range(len(a)))

def pinv(p):
    r = [0] * len(p)
    for i, j in enumerate(p):
        r[j] = i
    return tuple(r)

def pcomm(a, b):
    """P1 convention: [a,b] = a b a^-1 b^-1."""
    return pmul(pmul(a, b), pmul(pinv(a), pinv(b)))

def pidentity(n):
    return tuple(range(n))

def pparity(p):
    s = 0
    for i in range(len(p)):
        for j in range(i + 1, len(p)):
            if p[i] > p[j]:
                s ^= 1
    return s  # 0 = even, 1 = odd

def pclosure(gens, n):
    """Subgroup generated by permutation tuples (BFS)."""
    e = pidentity(n)
    seen = {e}
    frontier = [e]
    gl = list(gens)
    while frontier:
        x = frontier.pop()
        for g in gl:
            y = pmul(x, g)
            if y not in seen:
                seen.add(y)
                frontier.append(y)
    return seen

def pcomm_subgroup(X, Y, n):
    """[<X>,<Y>] given X, Y already closed subgroups (sets of tuples)."""
    return pclosure([pcomm(x, y) for x in X for y in Y], n)

def pderived(H, n, k=1):
    """k-th derived subgroup of the subgroup H (set of tuples)."""
    cur = set(H)
    for _ in range(k):
        cur = pclosure([pcomm(a, b) for a in cur for b in cur], n)
        if len(cur) == 1:
            break
    return cur

def cycles_to_perm(cycles, n):
    """1-indexed cycle notation -> 0-indexed tuple. cycles=[(1,2),(3,4)] etc."""
    r = list(range(n))
    for cyc in cycles:
        for i in range(len(cyc)):
            r[cyc[i] - 1] = cyc[(i + 1) % len(cyc)] - 1
    return tuple(r)

def an_conjugator(x, y, n):
    """An explicit g in A_n with g x g^-1 == y, or None (constructive class check)."""
    for g in itertools.permutations(range(n)):
        if pparity(g) == 0 and pmul(pmul(g, x), pinv(g)) == y:
            return g
    return None

# --------------------------------------------------------------------------
# Table-backed groups (identical semantics to the frozen sweep scripts)
# --------------------------------------------------------------------------

class Group:
    def __init__(self, name, elems, mul_fn, id_elem):
        self.name = name
        self.elems = list(elems)
        self.n = len(self.elems)
        self.idx = {e: i for i, e in enumerate(self.elems)}
        self.e = self.idx[id_elem]
        n = self.n
        tbl = np.empty((n, n), dtype=np.int32)
        for i, a in enumerate(self.elems):
            for j, b in enumerate(self.elems):
                tbl[i, j] = self.idx[mul_fn(a, b)]
        self.tbl = tbl
        inv = np.empty(n, dtype=np.int32)
        for i in range(n):
            inv[i] = int(np.where(tbl[i] == self.e)[0][0])
        self.inv = inv
        self.involutions = [i for i in range(n) if i != self.e and tbl[i, i] == self.e]
        self._closure_cache = {}
        self._derived_cache = {}
        self._commsub_cache = {}

    # -- sets are sorted numpy index arrays --
    def smul(self, A, B):
        return np.unique(self.tbl[np.ix_(A, B)])

    def sinv(self, A):
        return np.unique(self.inv[A])

    def closure(self, gens):
        key = frozenset(int(x) for x in gens)
        if key in self._closure_cache:
            return self._closure_cache[key]
        S = {self.e}
        frontier = [self.e]
        gl = sorted(set(int(x) for x in gens))
        while frontier:
            nf = []
            for x in frontier:
                for g in gl:
                    y = int(self.tbl[x, g])
                    if y not in S:
                        S.add(y)
                        nf.append(y)
            frontier = nf
        out = np.array(sorted(S), dtype=np.int32)
        self._closure_cache[key] = out
        return out

    def comm_set(self, A, B):
        """{[a,b] : a in A, b in B} as a set (vectorised)."""
        A = np.asarray(A, dtype=np.int32)
        B = np.asarray(B, dtype=np.int32)
        ab = self.tbl[np.ix_(A, B)]
        ai = self.inv[A][:, None]
        aba = self.tbl[ab, ai]
        bi = self.inv[B][None, :]
        abab = self.tbl[aba, bi]
        return np.unique(abab)

    def comm_subgroup(self, X, Y):
        """[<X>,<Y>] for SUBGROUPS X, Y (closed arrays): <{[x,y]}>."""
        key = (frozenset(int(i) for i in X), frozenset(int(i) for i in Y))
        if key in self._commsub_cache:
            return self._commsub_cache[key]
        out = self.closure(self.comm_set(X, Y))
        self._commsub_cache[key] = out
        return out

    def derived(self, H, k):
        """k-th derived subgroup of the subgroup H (closed array)."""
        cur = np.asarray(H, dtype=np.int32)
        for _ in range(k):
            key = frozenset(int(i) for i in cur)
            if key in self._derived_cache:
                cur = self._derived_cache[key]
            else:
                nxt = self.closure(self.comm_set(cur, cur))
                self._derived_cache[key] = nxt
                cur = nxt
            if len(cur) == 1:
                break
        return cur

def perm_mul(a, b):
    return tuple(a[b[i]] for i in range(len(a)))

def sym_group(n, name):
    elems = list(itertools.permutations(range(n)))
    return Group(name, elems, perm_mul, tuple(range(n)))

def alt_group(n, name):
    elems = [p for p in itertools.permutations(range(n)) if pparity(p) == 0]
    return Group(name, elems, perm_mul, tuple(range(n)))

def pgl2(q, name):
    def canon(m):
        for x in m:
            if x % q != 0:
                xi = pow(x, q - 2, q)
                return tuple((y * xi) % q for y in m)
        return None
    elems = set()
    for a in range(q):
        for b in range(q):
            for c in range(q):
                for d in range(q):
                    if (a * d - b * c) % q != 0:
                        elems.add(canon((a, b, c, d)))
    def mul(m1, m2):
        a, b, c, d = m1
        e_, f, g, h = m2
        return canon(((a * e_ + b * g) % q, (a * f + b * h) % q,
                      (c * e_ + d * g) % q, (c * f + d * h) % q))
    return Group(name, sorted(elems), mul, canon((1, 0, 0, 1)))

def involution_classes(G):
    """Conjugacy classes of involutions, ordered by first appearance in G.involutions."""
    seen = set()
    classes = []
    for i in G.involutions:
        if i in seen:
            continue
        cls = set()
        for g in range(G.n):
            cls.add(int(G.tbl[G.tbl[g, i], G.inv[g]]))
        cls &= set(G.involutions)
        classes.append(sorted(cls))
        seen |= cls
    return classes

def ambient_class_index(G, classes=None):
    """Map: involution index -> its class number (for mixed/mono checks)."""
    if classes is None:
        classes = involution_classes(G)
    out = {}
    for ci, cls in enumerate(classes):
        for i in cls:
            out[i] = ci
    return out

# --------------------------------------------------------------------------
# Per-step tree evaluation and the (a)/(T)/(S) gate checks
# --------------------------------------------------------------------------

def eval_tree(G, leaves):
    """Balanced binary tree; leaves = list of element indices (len = 2^d).
    Returns levels[lvl] = list of node dicts {V, H, alpha, leafset, children}."""
    d = int(np.log2(len(leaves)))
    assert 2 ** d == len(leaves)
    cur = []
    for s in leaves:
        V = np.unique(np.array([G.e, s], dtype=np.int32))
        H = G.closure([s])
        cur.append({"V": V, "H": H, "alpha": s, "leafset": (s,)})
    levels = [cur]
    for _lvl in range(1, d + 1):
        nxt = []
        for i in range(0, len(cur), 2):
            L, R = cur[i], cur[i + 1]
            VLi = G.sinv(L["V"])
            VRi = G.sinv(R["V"])
            V = G.smul(G.smul(G.smul(L["V"], R["V"]), VLi), VRi)
            H = G.closure(np.concatenate([L["H"], R["H"]]))
            aL, aR = L["alpha"], R["alpha"]
            alpha = int(G.tbl[G.tbl[G.tbl[aL, aR], G.inv[aL]], G.inv[aR]])
            nxt.append({"V": V, "H": H, "alpha": alpha,
                        "leafset": L["leafset"] + R["leafset"], "children": (L, R)})
        levels.append(nxt)
        cur = nxt
    return levels

def check_gate(G, gate, k):
    """Validity (a), tower (T) and saturation (S) at a gate of level k >= 2.
    Same mathematics as the frozen sweeps (there named (b) and (c))."""
    L, R = gate["children"]
    HLd = G.derived(L["H"], k - 1)
    HRd = G.derived(R["H"], k - 1)
    Hvk = G.derived(gate["H"], k)
    T_lhs = G.comm_subgroup(HLd, HRd)
    T_ok = (len(T_lhs) == len(Hvk)) and bool(np.array_equal(T_lhs, Hvk))
    WL = np.intersect1d(L["V"], HLd)
    WR = np.intersect1d(R["V"], HRd)
    S_lhs = G.closure(G.comm_set(WL, WR))
    S_rhs = G.comm_subgroup(G.closure(WL), G.closure(WR))
    S_ok = bool(np.array_equal(S_lhs, S_rhs))
    return {"a": gate["alpha"] != G.e, "T": T_ok, "S": S_ok,
            "sizes": (int(len(WL)), int(len(WR)), int(len(S_lhs)),
                      int(len(S_rhs)), int(len(T_lhs)), int(len(Hvk)))}

def leaf_str(G, i):
    """Legacy serialisation of a leaf (kept identical to the frozen sweeps)."""
    return str(G.elems[i])

STAT_KEYS = ("templates", "gates_k2plus", "T_and_S", "T_and_not_S", "not_T",
             "a_and_not_T", "T_and_not_a")

def sweep(G, depth, leaf_pool, seed=None, n_samples=None, tag="",
          record_sink=None, progress=None):
    """Run one sweep. Exhaustive if n_samples is None, else sampled with
    random.Random(seed) exactly as the frozen scripts (rng.choice per leaf).
    record_sink(record_dict) is called for every (T) and not (S) gate.
    Returns the stats dict."""
    nl = 2 ** depth
    stats = {k: 0 for k in STAT_KEYS}
    if n_samples is None:
        it = itertools.product(leaf_pool, repeat=nl)
        mode = "exhaustive"
    else:
        assert seed is not None, "sampled sweep requires a seed"
        rng = random.Random(seed)
        it = (tuple(rng.choice(leaf_pool) for _ in range(nl))
              for _ in range(n_samples))
        mode = "sampled"
    for leaves in it:
        stats["templates"] += 1
        levels = eval_tree(G, list(leaves))
        for k in range(2, depth + 1):
            for gi, gate in enumerate(levels[k]):
                stats["gates_k2plus"] += 1
                r = check_gate(G, gate, k)
                if r["a"] and not r["T"]:
                    stats["a_and_not_T"] += 1
                if r["T"] and not r["a"]:
                    stats["T_and_not_a"] += 1
                if not r["T"]:
                    stats["not_T"] += 1
                elif r["S"]:
                    stats["T_and_S"] += 1
                else:
                    stats["T_and_not_S"] += 1
                    if record_sink is not None:
                        record_sink({
                            "group": G.name, "depth": depth, "k": k,
                            "gate_path": "k%d/%d" % (k, gi),
                            "leaves": [leaf_str(G, s) for s in leaves],
                            "gate_leafset": [leaf_str(G, s) for s in gate["leafset"]],
                            "leaf_idx": [int(s) for s in leaves],
                            "gate_leaf_idx": [int(s) for s in gate["leafset"]],
                            "sizes": {"WL": r["sizes"][0], "WR": r["sizes"][1],
                                      "S_lhs": r["sizes"][2], "S_rhs": r["sizes"][3],
                                      "T_lhs": r["sizes"][4], "Hvk": r["sizes"][5]},
                        })
        if progress is not None and stats["templates"] % 5000 == 0:
            progress(stats)
    stats["mode"] = mode
    stats["tag"] = tag
    return stats

