def s5_p0_l4_sanity():
    """The P0 l=4 template over S5: <V(root) & A5> has order 60 and the root
    gate satisfies (a), (T) and (S). Returns True or raises AssertionError."""
    S5 = sym_group(5, "S5")
    def tp(i, j):
        p = list(range(5))
        p[i], p[j] = p[j], p[i]
        return tuple(p)
    l4 = [S5.idx[tp(0, 1)], S5.idx[tp(1, 2)], S5.idx[tp(2, 3)], S5.idx[tp(3, 4)]]
    lv = eval_tree(S5, l4)
    A5set = S5.derived(np.arange(S5.n, dtype=np.int32), 1)
    got = S5.closure(np.intersect1d(lv[2][0]["V"], A5set))
    assert len(got) == 60, "<V & A5> has order %d != 60" % len(got)
    r = check_gate(S5, lv[2][0], 2)
    assert r["a"] and r["T"] and r["S"], r
    return True

def core_selftest():
    """Small invariants: multiplication, inverses, closures, classes, levels."""
    # permutation arithmetic and the P1 commutator convention
    a, b = (1, 0, 2), (0, 2, 1)              # (0 1), (1 2) in S3
    assert pmul(a, b) == (1, 2, 0)           # (0 1)(1 2) = (0 1 2) under p(q(x))
    assert pmul(a, pinv(a)) == pidentity(3)
    assert pcomm(a, b) == pmul(pmul(a, b), pmul(pinv(a), pinv(b)))
    assert len(pclosure([a, b], 3)) == 6     # <(01),(12)> = S3
    # table-backed groups
    S4 = sym_group(4, "S4")
    assert S4.n == 24 and len(S4.involutions) == 9
    assert [len(c) for c in involution_classes(S4)] == [6, 3]
    A5 = alt_group(5, "A5")
    assert A5.n == 60 and len(A5.involutions) == 15
    assert [len(c) for c in involution_classes(A5)] == [15]
    S5 = sym_group(5, "S5")
    assert [len(c) for c in involution_classes(S5)] == [10, 15]
    # derived series through the tables agrees with the pure helpers
    tr = S4.involutions[0]
    H = S4.closure([tr, S4.involutions[1]])
    Hp = S4.derived(H, 1)
    Hset = {S4.elems[int(i)] for i in H}
    assert {S4.elems[int(i)] for i in Hp} == pderived(Hset, 4, 1)
    return True
