def mm(A, B):
    a, b, c, d = A; e, f, g, h = B
    return ((a*e+b*g) % 4, (a*f+b*h) % 4, (c*e+d*g) % 4, (c*f+d*h) % 4)
def det(M): a, b, c, d = M; return (a*d - b*c) % 4
