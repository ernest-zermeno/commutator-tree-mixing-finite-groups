#!/usr/bin/env python3
"""Exact maximal-subgroup checks for P1, paper/sec_rank_one.tex, prop:psl33-level.
Migrated from P2A; the history below explains the original correction.

Why: an earlier version of the remark (after cor:minimalsimple) claimed the parabolic
3^2:2S4 was the ONLY involution-containing maximal subgroup of PSL3(3).  That is false
by omission: the Aschbacher class-S maximal S4 = SO3(3) also contains involutions and
lies in no parabolic.  The exact level D = 5 nevertheless survives, because
dl(S4) = 3 < 5 and derived length is monotone under inclusion.  This script certifies
every computational claim of the corrected remark by brute force over SL3(3) = PSL3(3).

Checks:
  (1) |PSL3(3)| = 5616 (SL3(3) with trivial center); the 117 involutions (single
      class 2A) generate G.
  (2) SO3(3) = {M in SL3(3) : M^T M = I} has order 24, 9 involutions, derived
      length 3 (i.e. S4-like), is generated by its involutions, and fixes no point
      and no line of P^2(F3) => it is contained in no parabolic.
  (3) SO3(3) is MAXIMAL: <SO3, g> = G for every representative g of the double
      cosets SO3\\G/SO3 outside SO3 (exhaustive sweep).
  (4) The parabolic P = Stab([1:0:0]) has order 432 (= 3^2:2S4 = 3^2:GL2(3)),
      derived length 5, and is generated by its involutions, so D = 5 is attained.
      (The line stabilisers form the second parabolic class, image of the first
      under the graph automorphism g -> (g^T)^{-1}; same order/dl by duality.)
  (5) There is a SINGLE class of maximal S4: every S4 contains a unique normal
      Klein subgroup V and a maximal S4 equals N_G(V); all 234 Klein subgroups of
      G form one conjugacy class, each with |N_G(V)| = 24.

Completeness of the list of maximals (two parabolic classes, one class of S4, and
the odd-order Frobenius 13:3) is ATLAS / Bloom (Trans. AMS 127, 1967); checks
(2)-(5) certify the properties the remark uses.  Pure Python, no dependencies;
runtime a few minutes.
"""
import itertools

P = 3
def mmul(A, B):
    return tuple(tuple(sum(A[i][k]*B[k][j] for k in range(3)) % P for j in range(3)) for i in range(3))
def mT(A):
    return tuple(tuple(A[j][i] for j in range(3)) for i in range(3))
I3 = tuple(tuple(1 if i==j else 0 for j in range(3)) for i in range(3))
def det(A):
    return (A[0][0]*(A[1][1]*A[2][2]-A[1][2]*A[2][1])
          - A[0][1]*(A[1][0]*A[2][2]-A[1][2]*A[2][0])
          + A[0][2]*(A[1][0]*A[2][1]-A[1][1]*A[2][0])) % P
def minv(A):
    # adjugate; valid since det(A) = 1 for all elements of SL3(3)
    c = [[0]*3 for _ in range(3)]
    for i in range(3):
        for j in range(3):
            m = [[A[r][s] for s in range(3) if s != j] for r in range(3) if r != i]
            co = (m[0][0]*m[1][1] - m[0][1]*m[1][0]) % P
            c[j][i] = (co if (i+j) % 2 == 0 else -co) % P
    return tuple(tuple(r) for r in c)

# --- build SL3(3) = PSL3(3) (center trivial since gcd(3, q-1) = gcd(3,2) = 1) ---
els = []
rows = list(itertools.product(range(3), repeat=3))
# brute force over matrices with det 1: 3^9 = 19683 candidates
for a in itertools.product(rows, repeat=3):
    if det(a) == 1:
        els.append(a)
G = set(els)
print("|SL3(3)| =", len(G), "(expect 5616)")

invs = [g for g in G if g != I3 and mmul(g, g) == I3]
print("#involutions =", len(invs), "(ATLAS class 2A: expect 117)")

def closure(gens):
    gens = list(gens)
    seen = set(gens); frontier = list(gens)
    while frontier:
        nf = []
        for x in frontier:
            for s in gens:
                y = mmul(x, s)
                if y not in seen:
                    seen.add(y); nf.append(y)
        frontier = nf
    return seen

# (1) involutions generate G (take a few, then all if needed)
H = closure(invs[:6])
if len(H) != 5616:
    H = closure(invs)
print("<involutions> order =", len(H), "(expect 5616 => generate G)")

# (2) SO3(3)
so3 = [g for g in G if mmul(mT(g), g) == I3]
print("\n|SO3(3)| =", len(so3), "(expect 24)")
so3invs = [g for g in so3 if g != I3 and mmul(g, g) == I3]
print("#involutions in SO3(3) =", len(so3invs), "(S4 has 9)")
gen_so3 = closure(so3invs)
print("<involutions of SO3> order =", len(gen_so3), "(expect 24 => involution-generated)")

def derived_series_len(Hset):
    cur = set(Hset)
    dl = 0
    while len(cur) > 1:
        lst = list(cur)
        ivs = {x: minv(x) for x in lst}
        # derived subgroup = closure of all commutators
        comms = set()
        for x in lst:
            for y in lst:
                comms.add(mmul(mmul(x, y), mmul(ivs[x], ivs[y])))
        nxt = closure(list(comms)) if comms else {I3}
        if nxt == cur:
            return None  # perfect, not solvable
        cur = nxt
        dl += 1
        if dl > 10: return None
    return dl

dl_so3 = derived_series_len(gen_so3)
print("dl(SO3(3)) =", dl_so3, "(S4 => 3)")

# fixes no point / no line of P^2(F3)?
def norm(v):
    # normalize projectively: first nonzero coordinate = 1
    for x in v:
        if x:
            inv = 1 if x == 1 else 2
            return tuple((inv*y) % 3 for y in v)
    return v
pts = sorted({norm(v) for v in itertools.product(range(3), repeat=3) if v != (0, 0, 0)})
def act(g, v):
    return norm(tuple(sum(g[i][j]*v[j] for j in range(3)) % 3 for i in range(3)))
fixed_pts = [v for v in pts if all(act(g, v) == v for g in so3)]
# lines of P^2 = points of the dual plane: g acts on lines by (g^{-1})^T; a common
# fixed line exists iff SO3 has a common eigenvector in the dual action.
fixed_lines = [v for v in pts if all(act(mT(minv(g)), v) == v for g in so3)]
print("SO3 common fixed points in P^2:", len(fixed_pts), "| common fixed lines:", len(fixed_lines),
      "(expect 0, 0 => NOT inside any parabolic)")

# (3) maximality of SO3 via double-coset reps
so3set = set(so3)
reps = []
covered = set()
for g in els:
    if g in covered: continue
    reps.append(g)
    for a in so3:
        ag = mmul(a, g)
        for b in so3:
            covered.add(mmul(ag, b))
print("#double cosets SO3\\G/SO3 =", len(reps))
maximal = True
gens_so3 = so3invs
for g in reps:
    if g in so3set: continue
    Hg = closure(gens_so3 + [g])
    if len(Hg) != 5616:
        maximal = False
        print("  NOT maximal: <SO3,g> has order", len(Hg))
print("SO3(3) maximal in PSL3(3)?", maximal)

# (4) parabolic = stabilizer of the point [1:0:0]
e1 = norm((1, 0, 0))
Ppar = [g for g in els if act(g, e1) == e1]
print("\n|Stab(point)| =", len(Ppar), "(expect 432 = 3^2:GL2(3))")
Pinvs = [g for g in Ppar if g != I3 and mmul(g, g) == I3]
genP = closure(Pinvs)
print("<involutions of P> order =", len(genP), "(involution-generated iff = 432)")
dl_parabolic = derived_series_len(set(Ppar))
print("dl(P) =", dl_parabolic, "(claim: 5)")
assert set(Ppar) == genP
print("dl(<involutions of P>) =", dl_parabolic)

# (5) single class of maximal S4: classify Klein four-subgroups and their normalizers
v4s = set()
for i in range(len(invs)):
    a = invs[i]
    for j in range(i+1, len(invs)):
        b = invs[j]
        if mmul(a, b) == mmul(b, a):
            v4s.add(frozenset((I3, a, b, mmul(a, b))))
print("\n#Klein four-subgroups =", len(v4s), "(expect 234 = 5616/24)")
unseen = set(v4s)
classes = []
while unseen:
    V = next(iter(unseen))
    orbit = set()
    for g in els:
        gi = minv(g)
        orbit.add(frozenset(mmul(mmul(g, x), gi) for x in V))
    classes.append((V, orbit))
    unseen -= orbit
print("#G-classes of V4 =", len(classes), "sizes:", [len(o) for _, o in classes],
      "(expect one class of size 234)")
for k, (V, orbit) in enumerate(classes):
    N = [g for g in els if frozenset(mmul(mmul(g, x), minv(g)) for x in V) == V]
    assert len(N) == 24
    print(f"class {k}: |N_G(V)| = {len(N)} (expect 24 => every maximal S4 = N_G(V);"
          " single class of maximal S4)")

assert len(G) == 5616 and len(invs) == 117 and len(H) == 5616
assert len(so3) == len(gen_so3) == 24 and dl_so3 == 3
assert not fixed_pts and not fixed_lines and maximal
assert len(Ppar) == 432 and dl_parabolic == 5
assert len(v4s) == 234 and len(classes) == 1
print("PSL3(3) CERTIFICATE: PASS")
